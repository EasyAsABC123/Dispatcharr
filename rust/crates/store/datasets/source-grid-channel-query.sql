SELECT
  c.id AS c_id,
  c.channel_number AS c_channel_number,
  c.name AS c_name,
  c.logo_id AS c_logo_id,
  c.channel_group_id AS c_channel_group_id,
  c.tvg_id AS c_tvg_id,
  c.tvc_guide_stationid AS c_tvc_guide_stationid,
  c.epg_data_id AS c_epg_data_id,
  c.stream_profile_id AS c_stream_profile_id,
  c.uuid AS c_uuid,
  c.user_level AS c_user_level,
  c.is_adult AS c_is_adult,
  c.auto_created AS c_auto_created,
  c.auto_created_by_id AS c_auto_created_by_id,
  c.is_catchup AS c_is_catchup,
  c.catchup_days AS c_catchup_days,
  c.is_radio AS c_is_radio,
  c.hidden_from_output AS c_hidden_from_output,
  c.created_at AS c_created_at,
  c.updated_at AS c_updated_at,
  COALESCE(o.name, c.name) AS effective_name,
  COALESCE(o.channel_number, c.channel_number) AS effective_channel_number,
  COALESCE(o.channel_group_id, c.channel_group_id) AS effective_channel_group_id,
  COALESCE(o.logo_id, c.logo_id) AS effective_logo_id,
  COALESCE(o.tvg_id, c.tvg_id) AS effective_tvg_id,
  COALESCE(o.tvc_guide_stationid, c.tvc_guide_stationid) AS effective_tvc_guide_stationid,
  COALESCE(o.epg_data_id, c.epg_data_id) AS effective_epg_data_id,
  COALESCE(o.stream_profile_id, c.stream_profile_id) AS effective_stream_profile_id,
  COALESCE(o.is_radio, c.is_radio) AS effective_is_radio,
  be.id AS be_id,
  be.tvg_id AS be_tvg_id,
  be.name AS be_name,
  be.icon_url AS be_icon_url,
  be.epg_source_id AS be_epg_source_id,
  bs.id AS bs_id,
  bs.name AS bs_name,
  bs.source_type AS bs_source_type,
  bs.url AS bs_url,
  bs.username AS bs_username,
  bs.password AS bs_password,
  bs.is_active AS bs_is_active,
  bs.file_path AS bs_file_path,
  bs.extracted_file_path AS bs_extracted_file_path,
  bs.refresh_interval AS bs_refresh_interval,
  bs.refresh_task_id AS bs_refresh_task_id,
  bs.custom_properties AS bs_custom_properties,
  bs.priority AS bs_priority,
  bs.status AS bs_status,
  bs.last_message AS bs_last_message,
  bs.created_at AS bs_created_at,
  bs.updated_at AS bs_updated_at,
  o.id AS o_id,
  o.channel_id AS o_channel_id,
  o.name AS o_name,
  o.channel_number AS o_channel_number,
  o.channel_group_id AS o_channel_group_id,
  o.logo_id AS o_logo_id,
  o.tvg_id AS o_tvg_id,
  o.tvc_guide_stationid AS o_tvc_guide_stationid,
  o.epg_data_id AS o_epg_data_id,
  o.stream_profile_id AS o_stream_profile_id,
  o.is_radio AS o_is_radio,
  o.created_at AS o_created_at,
  o.updated_at AS o_updated_at,
  oe.id AS oe_id,
  oe.tvg_id AS oe_tvg_id,
  oe.name AS oe_name,
  oe.icon_url AS oe_icon_url,
  oe.epg_source_id AS oe_epg_source_id,
  os.id AS os_id,
  os.name AS os_name,
  os.source_type AS os_source_type,
  os.url AS os_url,
  os.username AS os_username,
  os.password AS os_password,
  os.is_active AS os_is_active,
  os.file_path AS os_file_path,
  os.extracted_file_path AS os_extracted_file_path,
  os.refresh_interval AS os_refresh_interval,
  os.refresh_task_id AS os_refresh_task_id,
  os.custom_properties AS os_custom_properties,
  os.priority AS os_priority,
  os.status AS os_status,
  os.last_message AS os_last_message,
  os.created_at AS os_created_at,
  os.updated_at AS os_updated_at
FROM dispatcharr_channels_channel c
LEFT OUTER JOIN dispatcharr_channels_channeloverride o ON c.id=o.channel_id
LEFT OUTER JOIN epg_epgdata oe ON o.epg_data_id=oe.id
LEFT OUTER JOIN epg_epgdata be ON c.epg_data_id=be.id
LEFT OUTER JOIN epg_epgsource bs ON be.epg_source_id=bs.id
LEFT OUTER JOIN epg_epgsource os ON oe.epg_source_id=os.id
WHERE TRUE
